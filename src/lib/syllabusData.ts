export function isStaticTopicId(id: string): boolean {
  return STATIC_TOPIC_IDS.has(id);
}

export function isStaticSubjectId(id: string): boolean {
  return STATIC_SUBJECT_IDS.has(id);
}

export function isStaticPaperId(id: string): boolean {
  return STATIC_PAPER_IDS.has(id);
}
